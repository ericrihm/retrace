# ---------------------------------------------------------------------------
# OpenOCD config generation
# ---------------------------------------------------------------------------

def generate_openocd_config(
    findings: list[dict[str, Any]],
    *,
    board_name: str = "unknown",
) -> str:
    """Generate an OpenOCD .cfg snippet for detected JTAG/SWD interfaces.

    Only JTAG and SWD interfaces produce meaningful OpenOCD configs.

    Args:
        findings: List of debug interface finding dicts.
        board_name: Board name for comments.

    Returns:
        OpenOCD config string, or empty string if no JTAG/SWD detected.
    """
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    configs: list[str] = []

    for finding in findings:
        interface = finding.get("interface", "")
        if interface not in ("JTAG", "SWD"):
            continue

        comp_label = finding.get("component_label", "")
        comp_marking = finding.get("component_marking", "")
        comp_ref = f"{comp_label} ({comp_marking})" if comp_marking else comp_label
        transport = "jtag" if interface == "JTAG" else "swd"

        cfg = _OPENOCD_INTERFACE_TEMPLATE.format(
            interface=interface,
            component_ref=comp_ref,
            timestamp=timestamp,
            transport=transport,
        )

        if interface == "JTAG":
            cfg += _OPENOCD_JTAG_EXTRAS
        elif interface == "SWD":
            cfg += _OPENOCD_SWD_EXTRAS

        configs.append(cfg)

    return "\n".join(configs)


# ---------------------------------------------------------------------------
# Combined export (convenience for CLI)
# ---------------------------------------------------------------------------

def export_jtagulator_configs(
    findings: list[dict[str, Any]],
    *,
    board_name: str = "unknown",
    voltage: str | None = None,
) -> dict[str, str]:
    """Generate all JTAGulator-related config files.

    Returns:
        Dict mapping filename to content:
        - "jtagulator.txt": JTAGulator pin config
        - "openocd.cfg": OpenOCD config (only if JTAG/SWD detected)
    """
    result: dict[str, str] = {}

    result["jtagulator.txt"] = generate_jtagulator_config(
        findings, board_name=board_name, voltage=voltage,
    )

    openocd = generate_openocd_config(findings, board_name=board_name)
    if openocd.strip():
        result["openocd.cfg"] = openocd

    return result
